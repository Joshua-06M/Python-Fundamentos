
automovil="Mazda"

print(automovil[3])

# para obtener la ultima letra es de la siguiente forma

print(automovil[-1])

# para hacer la impresion de una cierta parte [start : stop]

print(automovil[0:3])

# para hacer saltos de 2 en 2 o 3 en 3, etc se usa un stepover [start:stop:stepover]

print(automovil[0:3:2])

# para imprimirlo al reves

name_reverse=automovil[::-1]

print(name_reverse)