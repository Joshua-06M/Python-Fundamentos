#son los metodos de eliminacion

members_list=[1,2,3,4,5]
print(members_list)

#pop() quitar el ultimo elemento de la lista
members_list.pop()
members_list.pop(1) #quitar elemento que queremos 
print(members_list)

#remove
members_list.remove(4) #Elimina el numero que quieras

print(members_list)

#clear limpia por completo la lista
members_list.clear()
print(members_list)

